# Generates include/atomforge/zhou04_params.hpp from the LAMMPS EAM_code table
# (X.W. Zhou, R.A. Johnson, H.N.G. Wadley, PRB 69, 144113 (2004); Cr from Lin et al. PRB 77 214108 (2008))
import sys
fields = ["re","fe","rhoe","rhos","alpha","beta","A","B","cai","ramda","Fi0","Fi1","Fi2","Fi3",
          "Fm0","Fm1","Fm2","Fm3","fnn","Fn","Z","mass","Fm4","beta1","ramda1","rhol","rhoh"]
ground = {"Cu":"fcc","Ag":"fcc","Au":"fcc","Ni":"fcc","Pd":"fcc","Pt":"fcc","Al":"fcc","Pb":"fcc",
          "Fe":"bcc","Mo":"bcc","Ta":"bcc","W":"bcc","Cr":"bcc","Mg":"hcp","Co":"hcp","Ti":"hcp","Zr":"hcp"}
lines = [l.strip() for l in open(sys.argv[1]) if l.strip()]
out = []
i = 0
while i < len(lines):
    name = lines[i]; vals = lines[i+1:i+1+len(fields)]; i += 1+len(fields)
    v = dict(zip(fields, vals))
    out.append('    {"%s", %s, "%s"},' % (name, ", ".join(v[f] for f in fields), ground.get(name,"fcc")))
hdr = """// AUTO-GENERATED by tools/gen_params.py from LAMMPS tools/eam_database/EAM_code. Do not edit.
#pragma once
#include <array>
namespace atomforge::zhou04 {
struct Params {
    const char* name;
    double re, fe, rhoe, rhos, alpha, beta, A, B, cai, ramda;
    double Fi0, Fi1, Fi2, Fi3, Fm0, Fm1, Fm2, Fm3, fnn, Fn;
    int Z; double mass; double Fm4, beta1, ramda1, rhol, rhoh;
    const char* fitted_ground_state;
};
inline constexpr std::array<Params, %d> table = {{
%s
}};
} // namespace atomforge::zhou04
""" % (len(out), "\n".join(out))
open(sys.argv[2],"w").write(hdr)
print(len(out), "elements")
